/**
 * 거래처명으로 등록된 통장사본 정보 조회
 * @param {string} vendorName 
 * @returns {object|null}
 */
window.getVendorBankDoc = function(vendorName) {
  if (!vendorName || !window.VENDOR_BANK_DOCS) return null;
  const norm = typeof normalizeVendorName === 'function' ? normalizeVendorName(vendorName) : vendorName.trim();
  if (window.VENDOR_BANK_DOCS[norm]) return window.VENDOR_BANK_DOCS[norm];
  if (window.VENDOR_BANK_DOCS[vendorName]) return window.VENDOR_BANK_DOCS[vendorName];

  // 부분 일치 검사 (띄어쓰기/특수문자 제외)
  const clean = norm.replace(/[\s\-_,\(\)주]/g, '');
  if (!clean) return null;
  for (const k in window.VENDOR_BANK_DOCS) {
    const kClean = k.replace(/[\s\-_,\(\)주]/g, '');
    if (kClean.includes(clean) || clean.includes(kClean)) {
      return window.VENDOR_BANK_DOCS[k];
    }
  }
  return null;
};
